        "7:         if distance_i < 10.0 cm then state_i = 1 else state_i = 0\n"
        "8:         update_led(Pin_i, state_i)\n"
        "9:     end for\n"
        "10:    update_SSD1306_display(total_occupied, free_bays)\n"
        "11:    if timer >= 5000 ms then\n"
        "12:        publish_MQTT(payload_JSON)\n"
        "13:    end if\n"
        "14:    FastAPI backend aggregates readings across Zones A-E into SQLite\n"
        "15:    Extract 13-step temporal lags, rolling statistics, and cyclical sine-cosine encodings\n"
        "16:    Execute XGBoost inference for horizons: t+15m, t+30m, and t+60m\n"
        "17:    if prediction_30m >= 17 bays then dispatch saturation alert to Telegram and Dashboard\n"
        "18: end loop"
