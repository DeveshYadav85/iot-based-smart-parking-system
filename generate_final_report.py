        "Ultrasonic sensors are scanned iteratively every 1000 milliseconds. When an echo pulse return indicates a distance under 10.0 cm, the corresponding bay is marked as occupied. "
        "Every five seconds, a compact JSON telemetry payload is constructed and published to bmu/iotnaa/smartparking-g01/A/slotN."
