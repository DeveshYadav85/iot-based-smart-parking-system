        "Extreme Gradient Boosting (XGBoost) regression models were implemented for multi-horizon occupancy forecasting at +15 minutes (6 forward steps), +30 minutes (12 forward steps), and +60 minutes (24 forward steps). "
        "XGBoost constructs an ensemble of shallow decision trees iteratively, minimizing regularized squared loss gradients through second-order Taylor expansions. "
        "Hyperparameters were configured with 120 estimators, maximum tree depth of 5, learning rate of 0.08, subsample ratio of 0.8, and feature colsample ratio of 0.8. "
        "The dataset was split run-wise into 160 training runs (30,720 rows) and 40 unseen testing runs (7,680 rows) to ensure complete temporal independence during cross-validation."
