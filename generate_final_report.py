        "Zones B, C, D, and E (representing sixteen additional bays) are driven by a dynamic Python lot simulator to model a complete twenty-bay parking facility. "
        "Telemetry is published every five seconds over TCP port 1883 to the public HiveMQ MQTT broker under an isolated hierarchical topic namespace. "
